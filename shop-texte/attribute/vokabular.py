def uebersetze(werte, tabelle):
    """Liste EN -> DE. Unbekanntes bleibt stehen (wird im Bericht gemeldet)."""
    out=[];offen=[]
    for w in werte:
        w=w.strip()
        if not w: continue
        d=tabelle.get(w) or tabelle.get(w.title())
        if d: out.append(d)
        else:
            out.append(w[:1].upper()+w[1:]); offen.append(w)
    # Dubletten raus, Reihenfolge erhalten
    seen=set(); res=[]
    for x in out:
        if x not in seen: seen.add(x); res.append(x)
    return res, offen
